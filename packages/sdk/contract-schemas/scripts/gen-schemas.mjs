// Writes `schemas/<name>.json`: the wire contracts as JSON Schema 2020-12, generated from the Zod sources in src/ (ADR-0096).
//
//   node scripts/gen-schemas.mjs           regenerate schemas/*.json
//   node scripts/gen-schemas.mjs --check   fail when a committed file differs from src/, is missing or is stray (run by `pnpm test`)
//
// Node 26 strips types natively; src/ imports `zod/v4` and its own files with explicit `.ts` extensions, so no loader is needed.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../schemas/', import.meta.url);
const { SCHEMA_FILES, schemaFileText } = await import('../src/index.ts');

const expected = new Map(Object.entries(SCHEMA_FILES).map(([name, schema]) => [`${name}.json`, schemaFileText(schema)]));

if (process.argv.includes('--check')) {
  const problems = [];
  for (const [file, text] of expected) {
    const current = existsSync(new URL(file, dir)) ? readFileSync(new URL(file, dir), 'utf8') : null;
    if (current !== text) problems.push(`${file} is ${current === null ? 'missing' : 'out of date'}`);
  }
  for (const file of existsSync(dir) ? readdirSync(dir) : []) if (!expected.has(file)) problems.push(`${file} is not generated by src/`);
  if (problems.length > 0) {
    process.stderr.write(`schemas/ differs from src/ (${problems.join('; ')}) — run \`pnpm --filter @ap/contract-schemas gen:schemas\` and commit it\n`);
    process.exitCode = 1;
  } else {
    process.stdout.write('schemas/ is up to date\n');
  }
} else {
  mkdirSync(dir, { recursive: true });
  for (const [file, text] of expected) writeFileSync(new URL(file, dir), text);
  process.stdout.write(`wrote ${expected.size} schema files\n`);
}
