import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import type * as React from 'react';
import type { Editor } from '@tiptap/core';
import { describe, expect, it, vi } from 'vitest';
const drag = vi.hoisted(() => ({ change: (_value: { pos: number }) => {} }));
vi.mock('@tiptap/extension-drag-handle-react', () => ({ default: ({ children, onNodeChange }: { children: React.ReactNode; onNodeChange: typeof drag.change }) => { drag.change = onNodeChange; return <div data-testid="drag-handle">{children}</div>; } }));
import RichEditorImpl from '../RichEditorImpl';
async function mount() {
  let editor: Editor | null = null;
  const rendered = render(<RichEditorImpl surface="voc-description" ariaLabel="본문" toolbar={(live, api) => { editor = live; return api.renderControls?.(); }} />);
  await screen.findByRole('textbox', { name: '본문' });
  await waitFor(() => expect(editor).not.toBeNull());
  vi.spyOn(editor!.view, 'coordsAtPos').mockReturnValue({ top: 120, bottom: 140, left: 10, right: 10 });
  return { ...rendered, editor: editor! };
}
describe('block context controls', () => {
  it('gives table controls one Tab stop and shared arrow/Home/End navigation', async () => {
    const { editor } = await mount();
    act(() => { editor.commands.insertTable({ rows: 2, cols: 2 }); });
    const bar = await screen.findByRole('toolbar', { name: '표 편집' });
    const buttons = within(bar).getAllByRole('button').filter(button => !button.hasAttribute('disabled'));
    expect(buttons.filter(button => button.tabIndex === 0)).toHaveLength(1);
    act(() => buttons[0]!.focus());
    fireEvent.keyDown(buttons[0]!, { key: 'ArrowRight' });
    expect(buttons[1]).toHaveFocus();
    fireEvent.keyDown(buttons[1]!, { key: 'End' });
    expect(buttons.at(-1)).toHaveFocus();
    fireEvent.keyDown(buttons.at(-1)!, { key: 'ArrowRight' });
    expect(buttons[0]).toHaveFocus();
    fireEvent.keyDown(buttons[0]!, { key: 'ArrowLeft' });
    expect(buttons.at(-1)).toHaveFocus();
    fireEvent.keyDown(buttons.at(-1)!, { key: 'Home' });
    expect(buttons[0]).toHaveFocus();
  });
  it('does not mutate the ProseMirror-owned code node to reserve context space', async () => {
    const { editor } = await mount();
    act(() => { editor.commands.setContent('<p>before</p><pre><code>sample</code></pre>'); editor.commands.setTextSelection(2); });
    const code = editor.view.dom.querySelector('pre')!;
    let codePosition = 0;
    editor.state.doc.descendants((node, pos) => { if (node.type.name === 'codeBlock') codePosition = pos + 1; });
    act(() => { editor.commands.setTextSelection(codePosition); });
    await screen.findByRole('button', { name: '코드 언어' });
    expect(code).not.toHaveAttribute('data-rich-context');
    await act(async () => { await new Promise(resolve => setTimeout(resolve, 30)); });
    expect(editor.view.dom.querySelector('pre')).toBe(code);
    expect(code.isConnected).toBe(true);
  });
  it('moves table actions off the fixed rows and provides before/after, header, merge/split and deletion actions', async () => {
    const { editor } = await mount();
    act(() => { editor.commands.insertTable({ rows: 2, cols: 2 }); });
    const bar = await screen.findByRole('toolbar', { name: '표 편집' });
    expect(screen.getByRole('toolbar', { name: '본문 서식' })).not.toContainElement(bar);
    expect(bar.parentElement).toHaveAttribute('data-context-placement', 'top-start');
    for (const label of ['위에 행 추가', '아래에 행 추가', '왼쪽에 열 추가', '오른쪽에 열 추가', '행 삭제', '열 삭제', '머리 행', '칸 병합 / 나누기', '표 삭제']) expect(within(bar).getByRole('button', { name: label })).toBeInTheDocument();
    await userEvent.click(within(bar).getByRole('button', { name: '위에 행 추가' }));
    expect(editor.view.dom.querySelectorAll('tr')).toHaveLength(3);
    await userEvent.click(within(bar).getByRole('button', { name: '아래에 행 추가' }));
    expect(editor.view.dom.querySelectorAll('tr')).toHaveLength(4);
    await userEvent.click(within(bar).getByRole('button', { name: '왼쪽에 열 추가' }));
    expect(editor.view.dom.querySelector('tr')?.children).toHaveLength(3);
    await userEvent.click(within(bar).getByRole('button', { name: '오른쪽에 열 추가' }));
    expect(editor.view.dom.querySelector('tr')?.children).toHaveLength(4);
    await userEvent.click(within(bar).getByRole('button', { name: '열 삭제' }));
    expect(editor.view.dom.querySelector('tr')?.children).toHaveLength(3);
    await userEvent.click(within(bar).getByRole('button', { name: '행 삭제' }));
    expect(editor.view.dom.querySelectorAll('tr')).toHaveLength(3);
    await userEvent.click(within(bar).getByRole('button', { name: '머리 행' }));
    expect(editor.view.dom.querySelector('tr th')).not.toBeNull();
    await userEvent.click(within(bar).getByRole('button', { name: '표 삭제' }));
    expect(editor.view.dom.querySelector('table')).toBeNull();
  });
  it('merges a real two-cell selection and splits the merged cell from the context bar', async () => {
    const { editor } = await mount();
    act(() => { editor.commands.setContent('<table><tr><td><p>A</p></td><td><p>B</p></td></tr><tr><td><p>C</p></td><td><p>D</p></td></tr></table>'); });
    const cells: number[] = [];
    editor.state.doc.descendants((node, pos) => { if (node.type.name === 'tableCell') cells.push(pos); });
    act(() => { editor.commands.setCellSelection({ anchorCell: cells[0]!, headCell: cells[1]! }); });
    const bar = await screen.findByRole('toolbar', { name: '표 편집' });
    const mergeSplit = within(bar).getByRole('button', { name: '칸 병합 / 나누기' });
    expect(mergeSplit).toBeEnabled();
    await userEvent.click(mergeSplit);
    expect(editor.view.dom.querySelectorAll('td')).toHaveLength(3);
    const merged = editor.view.dom.querySelector('td');
    expect(merged).toHaveAttribute('colspan', '2');
    expect(merged).toHaveTextContent('AB');
    act(() => { editor.commands.setTextSelection(cells[0]! + 2); });
    expect(mergeSplit).toBeEnabled();
    await userEvent.click(mergeSplit);
    expect(editor.view.dom.querySelectorAll('td')).toHaveLength(4);
    expect(editor.view.dom.querySelector('[colspan="2"]')).toBeNull();
    expect(editor.view.dom.querySelectorAll('tr')).toHaveLength(2);
    expect(editor.view.dom.querySelectorAll('tr')[1]).toHaveTextContent('CD');
  });
  it('keeps the code chip anchor mounted while focus enters the portalled language menu and resets language to null', async () => {
    const { editor } = await mount();
    act(() => { editor.commands.toggleCodeBlock({ language: 'javascript' }); });
    const chip = await screen.findByRole('button', { name: '코드 언어' });
    const anchor = chip.closest('[data-context-placement]');
    expect(anchor).toHaveAttribute('data-context-placement', 'top-end');
    await userEvent.click(chip);
    const menu = screen.getByRole('menu');
    act(() => menu.focus());
    fireEvent.blur(editor.view.dom, { relatedTarget: menu });
    expect(chip).toBeInTheDocument();
    expect(chip.closest('[data-context-placement]')).toBe(anchor);
    expect(anchor).not.toHaveStyle({ display: 'none' });
    await userEvent.click(screen.getByRole('menuitemradio', { name: '일반 텍스트' }));
    expect(editor.getAttributes('codeBlock').language).toBeNull();
    await userEvent.click(chip);
    fireEvent.keyDown(screen.getByRole('menu'), { key: 'Escape' });
    await waitFor(() => expect(chip).toHaveFocus());
  });
  it('keeps the grip and runs the add action at the hovered block through its adjacent plus', async () => {
    const { editor } = await mount();
    act(() => { editor.commands.setContent('<p>first</p><p>second</p>'); editor.commands.setTextSelection(2); drag.change({ pos: 7 }); });
    const handle = screen.getByTestId('drag-handle');
    expect(within(handle).getByRole('button', { name: '블록 끌어 옮기기' })).toBeInTheDocument();
    expect(within(handle).getByRole('button', { name: '블록 끌어 옮기기' }).parentElement).toHaveClass('flex-col');
    await userEvent.click(within(handle).getByRole('button', { name: '블록 추가' }));
    await userEvent.click(screen.getByRole('menuitem', { name: '인용' }));
    expect(editor.getJSON().content?.map(node => node.type)).toEqual(['paragraph', 'blockquote', 'paragraph']);
    expect(editor.state.doc.child(1).textContent).toBe('second');
  });
  it('keeps slash options in the viewport on a long scrolled document', async () => {
    const { editor } = await mount();
    vi.spyOn(editor.view, 'coordsAtPos').mockReturnValue({ top: 5000, bottom: 5020, left: 10, right: 10 });
    act(() => { editor.commands.focus(); editor.commands.insertContent('/'); });
    const menu = await screen.findByRole('listbox', { name: '블록 추가' });
    expect(menu).toHaveClass('fixed');
    expect(parseFloat(menu.style.getPropertyValue('--rich-slash-top'))).toBeLessThan(window.innerHeight);
  });
  it('holds the stacked controls on their block while the pointer is on them', async () => {
    const { editor } = await mount();
    act(() => { editor.commands.setContent('<p>first</p><p>second</p>'); drag.change({ pos: 7 }); });
    const locks: unknown[] = [];
    editor.on('transaction', ({ transaction }) => { locks.push(transaction.getMeta('lockDragHandle')); });
    const stack = within(screen.getByTestId('drag-handle')).getByRole('button', { name: '블록 추가' }).closest('.flex-col')!;
    fireEvent.mouseEnter(stack);
    fireEvent.mouseLeave(stack);
    expect(locks).toEqual([true, false]);
  });
});
